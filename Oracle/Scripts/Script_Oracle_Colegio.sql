-- 3.1 Ver todas las columnas y filas de estudiantes
SELECT * FROM estudiantes;

-- 3.2 Ver solo algunas columnas
SELECT nombres, apellidos, documento
FROM estudiantes;

-- 3.3 Filtrar por curso con WHERE y una subconsulta
SELECT nombres, apellidos
FROM estudiantes
WHERE estudiante_id IN (
    SELECT estudiante_id
    FROM matriculas
    WHERE curso = '801'
);

-- 3.4 Ordenar alfabeticamente
SELECT nombres, apellidos
FROM estudiantes
ORDER BY apellidos ASC;

-- 3.5 Filtrar con AND
SELECT nombres, apellidos
FROM estudiantes
WHERE nombres LIKE 'A%'
  AND apellidos IS NOT NULL;

-- 3.6 Consultar matriculas y datos del estudiante (JOIN)
SELECT e.documento, e.nombres, e.apellidos,
       m.curso, m.anio_escolar, m.estado
FROM estudiantes e
INNER JOIN matriculas m
    ON e.estudiante_id = m.estudiante_id
ORDER BY m.curso, e.apellidos;

-- 3.7 Consultar calificaciones con estudiante, curso y asignatura (JOIN)
SELECT e.nombres, e.apellidos, m.curso,
       a.nombre AS asignatura, c.periodo, c.nota, c.observacion
FROM calificaciones c
INNER JOIN matriculas m
    ON c.matricula_id = m.matricula_id
INNER JOIN estudiantes e
    ON m.estudiante_id = e.estudiante_id
INNER JOIN asignaturas a
    ON c.asignatura_id = a.asignatura_id
ORDER BY e.apellidos, a.nombre, c.periodo;

-- 3.8 Consultar tambien el docente que dicta cada asignatura
SELECT a.nombre AS asignatura,
       d.nombres || ' ' || d.apellidos AS docente
FROM asignaturas a
INNER JOIN docentes d
    ON a.docente_id = d.docente_id
ORDER BY a.nombre;

-- 3.9 Funciones de agrupacion: promedio por estudiante
SELECT e.estudiante_id, e.nombres, e.apellidos,
       ROUND(AVG(c.nota), 2) AS promedio
FROM estudiantes e
INNER JOIN matriculas m
    ON e.estudiante_id = m.estudiante_id
INNER JOIN calificaciones c
    ON m.matricula_id = c.matricula_id
GROUP BY e.estudiante_id, e.nombres, e.apellidos
ORDER BY promedio DESC;

-- 3.10 Contar estudiantes por curso
SELECT m.curso, COUNT(*) AS cantidad_estudiantes
FROM matriculas m
WHERE m.estado = 'ACTIVA'
GROUP BY m.curso
ORDER BY m.curso;

-- 3.11 Mostrar promedios iguales o superiores a 4.0 (HAVING)
SELECT a.nombre AS asignatura, ROUND(AVG(c.nota), 2) AS promedio
FROM calificaciones c
INNER JOIN asignaturas a
    ON c.asignatura_id = a.asignatura_id
GROUP BY a.nombre
HAVING AVG(c.nota) >= 4.0;

