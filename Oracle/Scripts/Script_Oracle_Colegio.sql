/*
--------------------------------------------------------------------
SECCION 1. CREAR LAS CINCO TABLAS
--------------------------------------------------------------------
CREATE TABLE crea una tabla.
PRIMARY KEY identifica cada fila.
FOREIGN KEY relaciona tablas.
NOT NULL exige un valor.
UNIQUE evita valores repetidos.
CHECK valida una condicion.
IDENTITY genera identificadores automaticamente (Oracle 12c o posterior).
*/

-- 1. Tabla de docentes
CREATE TABLE docentes (
    docente_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombres VARCHAR2(60) NOT NULL,
    apellidos VARCHAR2(60) NOT NULL,
    correo VARCHAR2(100),
    CONSTRAINT pk_docentes PRIMARY KEY (docente_id),
    CONSTRAINT uq_docentes_correo UNIQUE (correo)
);

-- 2. Tabla de estudiantes
CREATE TABLE estudiantes (
    estudiante_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    documento VARCHAR2(20) NOT NULL,
    nombres VARCHAR2(60) NOT NULL,
    apellidos VARCHAR2(60) NOT NULL,
    fecha_nacimiento DATE,
    correo_acudiente VARCHAR2(100),
    CONSTRAINT pk_estudiantes PRIMARY KEY (estudiante_id),
    CONSTRAINT uq_est_documento UNIQUE (documento)
);

-- 3. Tabla de asignaturas. Cada asignatura tiene un docente.
CREATE TABLE asignaturas (
    asignatura_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(80) NOT NULL,
    intensidad_horaria NUMBER(2) NOT NULL,
    docente_id NUMBER NOT NULL,
    CONSTRAINT pk_asignaturas PRIMARY KEY (asignatura_id),
    CONSTRAINT uq_asig_nombre UNIQUE (nombre),
    CONSTRAINT ck_intensidad CHECK (intensidad_horaria BETWEEN 1 AND 40),
    CONSTRAINT fk_asig_docente FOREIGN KEY (docente_id)
        REFERENCES docentes(docente_id)
);

-- 4. Tabla de matriculas. Relaciona estudiantes con curso y año escolar.
CREATE TABLE matriculas (
    matricula_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    estudiante_id NUMBER NOT NULL,
    curso VARCHAR2(10) NOT NULL,
    anio_escolar NUMBER(4) NOT NULL,
    fecha_matricula DATE DEFAULT SYSDATE NOT NULL,
    estado VARCHAR2(15) DEFAULT 'ACTIVA' NOT NULL,
    CONSTRAINT pk_matriculas PRIMARY KEY (matricula_id),
    CONSTRAINT uq_estudiante_anio UNIQUE (estudiante_id, anio_escolar),
    CONSTRAINT ck_estado_matricula CHECK (estado IN ('ACTIVA', 'RETIRADA')),
    CONSTRAINT fk_mat_estudiante FOREIGN KEY (estudiante_id)
        REFERENCES estudiantes(estudiante_id)
);

-- 5. Tabla de calificaciones. Relaciona matriculas, asignaturas y periodos.
CREATE TABLE calificaciones (
    calificacion_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    matricula_id NUMBER NOT NULL,
    asignatura_id NUMBER NOT NULL,
    periodo NUMBER(1) NOT NULL,
    nota NUMBER(2,1) NOT NULL,
    observacion VARCHAR2(200),
    CONSTRAINT pk_calificaciones PRIMARY KEY (calificacion_id),
    CONSTRAINT uq_nota_periodo UNIQUE (matricula_id, asignatura_id, periodo),
    CONSTRAINT ck_nota CHECK (nota BETWEEN 0 AND 5),
    CONSTRAINT ck_periodo CHECK (periodo BETWEEN 1 AND 4),
    CONSTRAINT fk_cal_matricula FOREIGN KEY (matricula_id)
        REFERENCES matriculas(matricula_id),
    CONSTRAINT fk_cal_asignatura FOREIGN KEY (asignatura_id)
        REFERENCES asignaturas(asignatura_id)
);

