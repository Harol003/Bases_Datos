-- =========================================================
-- 1. TABLA: CLIENTES
-- Almacena la información de las personas que compran.
-- =========================================================

CREATE TABLE clientes (
    id_cliente NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombres VARCHAR2(60) NOT NULL,
    apellidos VARCHAR2(60) NOT NULL,
    telefono VARCHAR2(20),
    correo VARCHAR2(100),
    CONSTRAINT pk_clientes PRIMARY KEY (id_cliente),
    CONSTRAINT uq_clientes_correo UNIQUE (correo)
);


-- =========================================================
-- 2. TABLA: EMPLEADOS
-- Registra a las personas que trabajan en la bicicletería.
-- =========================================================

CREATE TABLE empleados (
    id_empleado NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombres VARCHAR2(60) NOT NULL,
    apellidos VARCHAR2(60) NOT NULL,
    cargo VARCHAR2(40) NOT NULL,
    salario NUMBER(10,2),
    CONSTRAINT pk_empleados PRIMARY KEY (id_empleado),
    CONSTRAINT ck_empleados_salario CHECK (salario >= 0)
);


-- =========================================================
-- 3. TABLA: CATEGORIAS
-- Clasifica los productos vendidos en el establecimiento.
-- =========================================================

CREATE TABLE categorias (
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(50) NOT NULL,
    descripcion VARCHAR2(200),
    CONSTRAINT pk_categorias PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categorias_nombre UNIQUE (nombre)
);


-- =========================================================
-- 4. TABLA: PRODUCTOS
-- Registra bicicletas, cascos, luces y otros artículos.
-- Cada producto pertenece a una categoría.
-- =========================================================

CREATE TABLE productos (
    id_producto NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(100) NOT NULL,
    marca VARCHAR2(50),
    precio NUMBER(10,2) NOT NULL,
    stock NUMBER(6) DEFAULT 0 NOT NULL,
    id_categoria NUMBER NOT NULL,

    CONSTRAINT pk_productos PRIMARY KEY (id_producto),

    CONSTRAINT fk_productos_categorias
        FOREIGN KEY (id_categoria)
        REFERENCES categorias(id_categoria),

    CONSTRAINT ck_productos_precio CHECK (precio >= 0),
    CONSTRAINT ck_productos_stock CHECK (stock >= 0)
);


-- =========================================================
-- 5. TABLA: VENTAS
-- Registra cada venta realizada.
-- Se relaciona con un cliente y un empleado.
-- =========================================================

CREATE TABLE ventas (
    id_venta NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fecha DATE DEFAULT SYSDATE NOT NULL,
    id_cliente NUMBER NOT NULL,
    id_empleado NUMBER NOT NULL,
    metodo_pago VARCHAR2(20) NOT NULL,

    CONSTRAINT pk_ventas PRIMARY KEY (id_venta),

    CONSTRAINT fk_ventas_clientes
        FOREIGN KEY (id_cliente)
        REFERENCES clientes(id_cliente),

    CONSTRAINT fk_ventas_empleados
        FOREIGN KEY (id_empleado)
        REFERENCES empleados(id_empleado),

    CONSTRAINT ck_ventas_pago
        CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA'))
);


-- =========================================================
-- 6. TABLA: DETALLE_VENTAS
-- Registra los productos y las cantidades de cada venta.
-- Una venta puede incluir varios productos.
-- =========================================================

CREATE TABLE detalle_ventas (
    id_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_venta NUMBER NOT NULL,
    id_producto NUMBER NOT NULL,
    cantidad NUMBER(6) NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL,

    CONSTRAINT pk_detalle_ventas PRIMARY KEY (id_detalle),

    CONSTRAINT fk_detalle_ventas
        FOREIGN KEY (id_venta)
        REFERENCES ventas(id_venta),

    CONSTRAINT fk_detalle_productos
        FOREIGN KEY (id_producto)
        REFERENCES productos(id_producto),

    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario >= 0)
);


