-- =========================================================
-- 15. CONSULTAR PRODUCTOS CON SU CATEGORÍA
-- =========================================================

SELECT
    p.id_producto,
    p.nombre AS producto,
    p.marca,
    p.precio,
    p.stock,
    c.nombre AS categoria
FROM productos p
INNER JOIN categorias c
    ON p.id_categoria = c.id_categoria
ORDER BY c.nombre, p.nombre;


-- =========================================================
-- 16. BUSCAR PRODUCTOS CON POCA EXISTENCIA
-- Muestra los productos que tienen cinco unidades o menos.
-- =========================================================

SELECT nombre, stock
FROM productos
WHERE stock <= 5
ORDER BY stock;


-- =========================================================
-- 17. CONSULTAR LAS VENTAS CON NOMBRE DEL CLIENTE
-- =========================================================

SELECT
    v.id_venta,
    v.fecha,
    c.nombres || ' ' || c.apellidos AS cliente,
    e.nombres || ' ' || e.apellidos AS empleado,
    v.metodo_pago
FROM ventas v
INNER JOIN clientes c
    ON v.id_cliente = c.id_cliente
INNER JOIN empleados e
    ON v.id_empleado = e.id_empleado
ORDER BY v.fecha DESC;


-- =========================================================
-- 18. CONSULTAR EL DETALLE Y TOTAL DE CADA VENTA
-- El total se calcula multiplicando cantidad por precio.
-- =========================================================

SELECT
    v.id_venta,
    c.nombres || ' ' || c.apellidos AS cliente,
    p.nombre AS producto,
    d.cantidad,
    d.precio_unitario,
    d.cantidad * d.precio_unitario AS subtotal
FROM ventas v
INNER JOIN clientes c
    ON v.id_cliente = c.id_cliente
INNER JOIN detalle_ventas d
    ON v.id_venta = d.id_venta
INNER JOIN productos p
    ON d.id_producto = p.id_producto
ORDER BY v.id_venta, p.nombre;


-- =========================================================
-- 19. CALCULAR EL TOTAL DE CADA VENTA
-- =========================================================

SELECT
    v.id_venta,
    c.nombres || ' ' || c.apellidos AS cliente,
    SUM(d.cantidad * d.precio_unitario) AS total_venta
FROM ventas v
INNER JOIN clientes c
    ON v.id_cliente = c.id_cliente
INNER JOIN detalle_ventas d
    ON v.id_venta = d.id_venta
GROUP BY v.id_venta, c.nombres, c.apellidos
ORDER BY v.id_venta;


